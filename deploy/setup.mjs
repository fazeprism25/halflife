// Creates deploy/.env with freshly generated local secrets (tokens and virtual keys) if it does
// not exist, and adds any that are missing. Provider credentials are NOT generated: add your own
// TAVILY_API_KEY and one LLM key (e.g. DEEPSEEK_API_KEY or OPENAI_API_KEY) to deploy/.env yourself.
// An existing file gains empty placeholder lines for the main provider keys it lacks.
//
//   node deploy/setup.mjs
// Prints only variable NAMES, never values.

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const file = path.join(import.meta.dirname, ".env");
const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
const has = (k) => new RegExp(`^${k}=.+`, "m").test(existing);
const rnd = (n = 24) => crypto.randomBytes(n).toString("base64url");

const generated = {
  HALFLIFE_INGEST_TOKEN: rnd(),
  HALFLIFE_INTERNAL_TOKEN: rnd(),
  HALFLIFE_RELAY_TOKEN: rnd(),
  BIFROST_ADMIN_TOKEN: rnd(),
  HALFLIFE_ENGINE_VK: "sk-bf-" + rnd(18),
  HALFLIFE_DEMO_VK: "sk-bf-" + rnd(18),
};

const lines = [];
const added = [];
for (const [k, v] of Object.entries(generated)) {
  if (!has(k)) {
    lines.push(`${k}=${v}`);
    added.push(k);
  }
}
const template = [
  "# --- provider credentials: fill in (never commit this file) ---",
  "TAVILY_API_KEY=",
  "DEEPSEEK_API_KEY=",
  "OPENAI_API_KEY=",
  "# ANTHROPIC_API_KEY=",
  "# GEMINI_API_KEY=",
  "# GROQ_API_KEY=",
  "# OPENROUTER_API_KEY=",
  "# --- optional overrides ---",
  "# HALFLIFE_LLM_MODEL=deepseek/deepseek-flash",
  "# HALFLIFE_LLM_FALLBACKS=deepseek/deepseek-v4-pro",
  "# HALFLIFE_PLAYGROUND_MODELS=deepseek/deepseek-flash",
  "# HALFLIFE_DAILY_CREDIT_CAP=150",
  "# HALFLIFE_ENGINE_BUDGET_USD=2",
  "# HALFLIFE_CACHE_TTL_SECONDS=3600",
  "# HALFLIFE_CONSOLE_TOKEN=",
  "# HALFLIFE_OLLAMA_URL=http://host.docker.internal:11434",
];
let out = existing;
if (!existing) out = "# Halflife local secrets, generated by deploy/setup.mjs\n" + template.join("\n") + "\n";
const placeholders = ["TAVILY_API_KEY", "DEEPSEEK_API_KEY"].filter((k) => !new RegExp(`^${k}=`, "m").test(out));
if (placeholders.length) out = out.replace(/\n?$/, "\n") + "# --- provider credentials: fill in (never commit this file) ---\n" + placeholders.map((k) => `${k}=`).join("\n") + "\n";
if (lines.length) out = out.replace(/\n?$/, "\n") + "# --- generated local secrets ---\n" + lines.join("\n") + "\n";
fs.writeFileSync(file, out, { mode: 0o600 });
console.log(added.length ? `deploy/.env: generated ${added.join(", ")}` : "deploy/.env: all local secrets already present");
const missing = ["TAVILY_API_KEY"].filter((k) => !has(k) && !new RegExp(`^${k}=.+`, "m").test(out));
const llm = ["DEEPSEEK_API_KEY", "OPENAI_API_KEY", "ANTHROPIC_API_KEY", "GEMINI_API_KEY", "GROQ_API_KEY", "OPENROUTER_API_KEY", "MISTRAL_API_KEY"].some((k) => new RegExp(`^${k}=.+`, "m").test(out));
if (missing.length) console.log(`deploy/.env: add ${missing.join(", ")} to enable live verification`);
if (!llm) console.log("deploy/.env: add one LLM provider key (e.g. DEEPSEEK_API_KEY) to enable model extraction and verdicts");
